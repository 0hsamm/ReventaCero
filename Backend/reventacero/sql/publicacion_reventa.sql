-- Boletas que un revendedor publica para que cualquier usuario las compre.
-- Ejecutar una vez, como script completo, en el esquema reventacero.

CREATE SEQUENCE SEQ_PUBLICACION_REVENTA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE PUBLICACION_REVENTA (
    ID_PUBLICACION      NUMBER        NOT NULL,
    FECHA_PUBLICACION   TIMESTAMP     NOT NULL,
    PRECIO              NUMBER(14, 2) NOT NULL,
    ESTADO              VARCHAR2(20)  NOT NULL,
    FECHA_CIERRE        TIMESTAMP,
    CODIGO_BOLETA       NUMBER        NOT NULL,
    VENDEDOR_DOCUMENTO  NUMBER        NOT NULL,
    COMPRADOR_DOCUMENTO NUMBER,
    CONSTRAINT PK_PUBLICACION_REVENTA PRIMARY KEY (ID_PUBLICACION),
    CONSTRAINT CK_PUBLICACION_REVENTA_ESTADO
        CHECK (ESTADO IN ('DISPONIBLE', 'VENDIDA', 'RETIRADA')),
    CONSTRAINT CK_PUBLICACION_REVENTA_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT FK_PUBLICACION_REVENTA_BOLETA
        FOREIGN KEY (CODIGO_BOLETA) REFERENCES BOLETA (CODIGO_BOLETA),
    CONSTRAINT FK_PUBLICACION_REVENTA_VENDEDOR
        FOREIGN KEY (VENDEDOR_DOCUMENTO) REFERENCES USUARIO (DOCUMENTO),
    CONSTRAINT FK_PUBLICACION_REVENTA_COMPRADOR
        FOREIGN KEY (COMPRADOR_DOCUMENTO) REFERENCES USUARIO (DOCUMENTO)
);

-- Una boleta solo puede estar publicada una vez a la vez.
CREATE UNIQUE INDEX UQ_PUBLICACION_REVENTA_ACTIVA
    ON PUBLICACION_REVENTA (CASE WHEN ESTADO = 'DISPONIBLE' THEN CODIGO_BOLETA END);

CREATE INDEX IX_PUBLICACION_REVENTA_VENDEDOR ON PUBLICACION_REVENTA (VENDEDOR_DOCUMENTO);
