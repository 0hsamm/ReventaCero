-- Solicitudes de reventa: la boleta solo cambia de dueño cuando el receptor acepta.
-- Ejecutar una vez en el esquema reventacero antes de iniciar esta versión del backend.

CREATE SEQUENCE SEQ_SOLICITUD_REVENTA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SOLICITUD_REVENTA (
    ID_SOLICITUD        NUMBER        NOT NULL,
    FECHA_HORA          TIMESTAMP     NOT NULL,
    PRECIO              NUMBER(14, 2) NOT NULL,
    METODO_PAGO         VARCHAR2(100) NOT NULL,
    ESTADO              VARCHAR2(20)  NOT NULL,
    FECHA_RESPUESTA     TIMESTAMP,
    CODIGO_BOLETA       NUMBER        NOT NULL,
    VENDEDOR_DOCUMENTO  NUMBER        NOT NULL,
    COMPRADOR_DOCUMENTO NUMBER        NOT NULL,
    CONSTRAINT PK_SOLICITUD_REVENTA PRIMARY KEY (ID_SOLICITUD),
    CONSTRAINT CK_SOLICITUD_REVENTA_ESTADO
        CHECK (ESTADO IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CANCELADA')),
    CONSTRAINT CK_SOLICITUD_REVENTA_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT FK_SOLICITUD_REVENTA_BOLETA
        FOREIGN KEY (CODIGO_BOLETA) REFERENCES BOLETA (CODIGO_BOLETA),
    CONSTRAINT FK_SOLICITUD_REVENTA_VENDEDOR
        FOREIGN KEY (VENDEDOR_DOCUMENTO) REFERENCES USUARIO (DOCUMENTO),
    CONSTRAINT FK_SOLICITUD_REVENTA_COMPRADOR
        FOREIGN KEY (COMPRADOR_DOCUMENTO) REFERENCES USUARIO (DOCUMENTO)
);

-- Una boleta solo puede tener una solicitud pendiente a la vez.
CREATE UNIQUE INDEX UQ_SOLICITUD_REVENTA_PENDIENTE
    ON SOLICITUD_REVENTA (CASE WHEN ESTADO = 'PENDIENTE' THEN CODIGO_BOLETA END);

CREATE INDEX IX_SOLICITUD_REVENTA_COMPRADOR ON SOLICITUD_REVENTA (COMPRADOR_DOCUMENTO);
CREATE INDEX IX_SOLICITUD_REVENTA_VENDEDOR ON SOLICITUD_REVENTA (VENDEDOR_DOCUMENTO);
